#include <stdio.h>

int alt_sum(int arr[], int n)
{
    if (n == 0)
    {
        return 0;
    }

    if ((n-1) % 2 == 0)
    {
        return arr[n - 1] + alt_sum(arr, n - 1);
    }
    else
    {
        return -arr[n - 1] + alt_sum(arr, n - 1);
    }
}

int main()
{
    int arr[5] = { 10, 20, 30, 40, 50 };
    int total = alt_sum(arr, 5);
    printf("交替和 = %d\n", total);
    return 0;
}