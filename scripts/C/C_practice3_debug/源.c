//分析原因
//你定义的数组是 int arr[5] = {1, 2, 3, 4, 5};
//C语言规定，数组的合法下标是 0, 1, 2, 3, 4。一共 5 个元素。
//arr[5] 代表的是数组后面的那一块内存。这块内存不属于此数组，
//里面存放的可能是其他变量的值，也可能是编译器留下的无意义垃圾数据（这恰好是一个很大的负数）。
//当执行 arr[i] = arr[i] * 2;（此时 i = 5），你实际上是在往不属于你的内存里写数据

//循环条件 i < 6 会让 i 取到0,1,2,3,4,5
//要让循环只遍历 5 个元素（下标 0 到 4）,i<6应改成i<5

#include <stdio.h>

int main() 
{
    int arr[5] = { 1, 2, 3, 4, 5 };
    int sum = 0;
    int i;

    for (i = 0; i < 5; i++) 
    {    
        arr[i] = arr[i] * 2;
        sum = sum + arr[i];
    }

    printf("sum = %d\n", sum);
    printf("i = %d\n", i);

    printf("数组内容：");
    for (i = 0; i < 5; i++) 
    {
        printf("%d ", arr[i]);
    }
    printf("\n");

    return 0;
}